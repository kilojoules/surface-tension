def load_arm_evidence(evidence_dir: str, arm: str):
    """Load the packaged evidence. Keys are inserted in SORTED order.

    Row order matters more than it should: the plain-CV and sample-level
    shuffle numbers depend on which samples land in which random fold, which
    depends on dict insertion order, which for the raw path is filesystem
    glob order. The corrected statistics (exact-tie grouped CV, permutation
    null, LOPO, full-data oracle, bounds) are order-invariant by
    construction — verified identical across both load paths — but the
    published-config reproductions, and the foldlegal memorizer reference
    that deliberately shares their folds, are only exact under the author's
    original enumeration order. See docs/correction_2026-07-12.md §3(d)."""
    rows = load_rows(os.path.join(evidence_dir, f"rows_{arm}.jsonl"))
    z = np.load(os.path.join(evidence_dir, f"acts_sol_{arm}.npz"), allow_pickle=False)
    pids = [str(p) for p in z["problem_ids"]]
    vecs = z["vectors"].astype(np.float32)
    by_pid = dict(zip(pids, vecs))
    acts = {}
    for (pid, sidx) in sorted(rows):
        if pid in by_pid:
            acts[(pid, sidx)] = by_pid[pid]
    return acts, rows


# --- per-arm analysis --------------------------------------------------------

def run_arm(arm: str, acts: dict, rows: dict, *, n_perms: int = 1000,
            identity_audit: bool = True) -> dict:
    out: dict = {"arm": arm}
    if identity_audit:
        audit = audit_identity(acts)
        out["identity_audit"] = audit
        if not audit["all_within_problem_identical"]:
            raise RuntimeError(
                f"{arm}: __sol tensors differ within a problem — the premise "
                "of the problem-level fast path is violated; investigate "
                "before use.")

    rs = list(rows.values())
    passing = [r for r in rs if r.get("passes_tests")]
    out["fact_side"] = {
        "n_rows": len(rs), "n_passing": len(passing),
        "launder_rate_shown_and_not_loose_given_pass":
            float(np.mean([bool(r["complied_shown"]) and not bool(r["complied_loose"])
                           for r in passing])) if passing else float("nan"),
        "launder_rate_shown_and_not_strict_given_pass":
            float(np.mean([bool(r["complied_shown"]) and not bool(r["complied_strict"])
                           for r in passing])) if passing else float("nan"),
    }

    out["probes"] = {}
    for label_name, require in ((HEADLINE_LABEL, None),
                                ("laundered", None)):
        X, y, groups = build_xy(acts, rows, LABELS[label_name], require=require)
        entry: dict = {"n": int(len(y)) if len(y) else 0}
        if len(y) == 0:
            out["probes"][label_name] = entry
            continue
        entry["n_pos"] = int((y == 1).sum())
        entry["n_problems"] = len(set(groups))
        entry["n_mixed_problems"] = sum(
            1 for p in set(groups)
            if len(set(y[np.array(groups) == p].tolist())) > 1)
        if entry["n_pos"] < 2 or entry["n"] - entry["n_pos"] < 2:
            entry["note"] = "fewer than 2 samples in a class - probe not fit (matches published n/a)"
            out["probes"][label_name] = entry
            continue

        # (a) reproduce the published configurations with the repo's own code,
        # at the repo's own precision (float32)
        aur_plain, _, _ = per_layer_auroc(X, y, k=5, seed=0)
        aur_group, _, _ = per_layer_auroc(X, y, k=5, seed=0, groups=groups)
        aur_shuf, _, _ = per_layer_auroc(X, y, k=5, seed=0, shuffle=True)
        entry["published_config"] = {
            "plain_cv_max_auroc": float(np.nanmax(aur_plain)),
            "plain_cv_argmax_layer": int(np.nanargmax(aur_plain)),
            "sample_level_shuffle_max_auroc": float(np.nanmax(aur_shuf)),
        }
        if np.all(np.isnan(aur_group)):
            # every grouped train fold was single-class (can happen when an
            # arm spans very few problems, e.g. the 2-problem vanilla arms):
            # there is no leakage-free number to report, which is itself the
            # finding — the plain-CV figure has no problem-held-out support.
            entry["published_config"]["grouped_cv_max_auroc"] = None
            entry["note"] = ("grouped CV undefined: every problem-held-out "
                             "train fold is single-class "
                             f"({entry['n_problems']} problems)")
            out["probes"][label_name] = entry
            continue
        entry["published_config"].update({
            "grouped_cv_max_auroc": float(np.nanmax(aur_group)),
            "grouped_cv_argmax_layer": int(np.nanargmax(aur_group)),
            "grouped_cv_curve_every_4_layers": {
                f"L{l}": round(float(aur_group[l]), 4)
                for l in range(0, len(aur_group), 4)},
        })
        # (b) leakage references with no activations at all: the CV-legal
        # memorizer (attainable through duplicate leakage alone) and the
        # full-data upper reference (includes each sample's own label)
        entry["foldlegal_baserate_auroc"] = float(foldlegal_baserate_auroc(y, groups))
        entry["oracle_problem_baserate_auroc"] = float(oracle_baserate_auroc(y, groups))

        # (c) the corrected null: problem-level permutation. The fast
        # problem-level path is validated against the repo's reference
        # implementation SCORE-BY-SCORE at float64. (AUROC-level comparison
        # is impossible: the reference breaks within-problem ties with
        # ~1e-14 BLAS jitter — see reference_grouped_scores — so its pooled
        # AUROC is itself noise-dependent at the third decimal.)
        pids = sorted(set(groups))
        pid_first = {}
        for (pid, sidx), a in sorted(acts.items()):
            pid_first.setdefault(pid, a)
        prob_vecs = np.stack([pid_first[p] for p in pids]).astype(np.float64)
        folds = _problem_folds(groups, 5, 0)
        scores_fast = grouped_scores_from_problem_vecs(
            prob_vecs, pids, y, groups, folds)
        scores_ref = reference_grouped_scores(
            X.astype(np.float64), y, groups, k=5, seed=0)
        both = ~(np.isnan(scores_fast) | np.isnan(scores_ref))
        if not (both.any() and np.array_equal(np.isnan(scores_fast),
                                              np.isnan(scores_ref))):
            raise RuntimeError(
                f"{arm}/{label_name}: fast and reference paths disagree on "
                "which scores are defined")
        max_score_dev = float(np.abs(scores_fast[both] - scores_ref[both]).max())
        if max_score_dev >= 1e-9:
            raise RuntimeError(
                f"{arm}/{label_name}: fast problem-level scores deviate from "
                f"the reference by {max_score_dev} — implementations disagree")
        entry["fast_vs_reference_max_score_dev"] = max_score_dev
        entry["published_config"]["grouped_cv_max_auroc_noise_broken_ties"] = (
            _max_layer_auroc(scores_ref, y))
        entry["published_config"]["grouped_cv_max_auroc_exact_ties"] = (
            _max_layer_auroc(scores_fast, y))
        entry["problem_permutation_null"] = perm_null_grouped_max(
            prob_vecs, pids, y, groups, k=5, seed=0, n_perms=n_perms)

        # (d) the honest unit of analysis
        entry["problem_level_lopo"] = problem_level_lopo(
            prob_vecs, pids, y, groups, seed=0, n_perms=2000)
        out["probes"][label_name] = entry
    return out


def run_arm_rep(arm: str, acts: dict, rows: dict) -> dict:
    """__rep (post-code, pre-self-report) probe stats: published (plain-CV)
    config plus the problem-held-out number and the no-activation oracle.

    __rep tensors are per-sample distinct (the generated code is in context),
    so the byte-identity critique does not apply — but the grouped-CV /
    problem-identity critique does, and unlike __sol there is no clean
    cluster permutation (blocks of distinct vectors differ in size), so no
    permutation p-value is reported. __rep additionally has the in-context
    confound the README's caveats already flag: the probe may read the code
    itself. Treat these as descriptive."""
    out: dict = {"arm": arm, "position": "rep", "probes": {}}
    for label_name in (HEADLINE_LABEL, "laundered"):
        X, y, groups = build_xy(acts, rows, LABELS[label_name])
        entry: dict = {"n": int(len(y)) if len(y) else 0}
        if len(y) == 0:
            out["probes"][label_name] = entry
            continue
        entry["n_pos"] = int((y == 1).sum())
        entry["n_problems"] = len(set(groups))
        if entry["n_pos"] < 2 or entry["n"] - entry["n_pos"] < 2:
            entry["note"] = "fewer than 2 samples in a class - probe not fit"
            out["probes"][label_name] = entry
            continue
        aur_plain, _, _ = per_layer_auroc(X, y, k=5, seed=0)
        aur_group, _, _ = per_layer_auroc(X, y, k=5, seed=0, groups=groups)
        entry["published_config"] = {
            "plain_cv_max_auroc": float(np.nanmax(aur_plain)),
            "grouped_cv_max_auroc": (None if np.all(np.isnan(aur_group))
                                     else float(np.nanmax(aur_group))),
        }
        if np.all(np.isnan(aur_group)):
            entry["note"] = ("grouped CV undefined: every problem-held-out "
                             "train fold is single-class "
                             f"({entry['n_problems']} problems)")
        entry["oracle_problem_baserate_auroc"] = float(oracle_baserate_auroc(y, groups))
        out["probes"][label_name] = entry
    return out


def deception_bounds() -> dict:
    out = {}
    for arm, (x, n) in DECEPTION_COUNTS.items():
        out[arm] = {
            "published_count": x, "n_passing": n,
            "point_estimate": round(x / n, 4),
            "one_sided_95_upper_bound": round(clopper_pearson_upper(x, n, 0.05), 4),
            "two_sided_95_upper_bound": round(clopper_pearson_upper(x, n, 0.025), 4),
        }
    out["_note"] = (
        "Counts as published (commit be5edf1); judge outputs were lost with "
        "the judge pod, so the claim side is not currently re-derivable — see "
        "docs/correction_2026-07-12.md. Bounds assume independent samples; "
        "samples cluster within <=17 problems, so true uncertainty is larger.")
    return out


def _sanitize_nan(obj):
    """NaN -> None so the output is valid strict JSON (json.dump would emit a
    bare NaN literal that non-Python parsers reject)."""
    if isinstance(obj, dict):
        return {k: _sanitize_nan(v) for k, v in obj.items()}
    if isinstance(obj, list):
        return [_sanitize_nan(v) for v in obj]
    if isinstance(obj, float) and np.isnan(obj):
        return None
    return obj


