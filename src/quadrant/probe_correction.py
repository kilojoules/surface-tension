def clopper_pearson_upper(x: int, n: int, alpha: float = 0.05) -> float:
    """One-sided (1-alpha) exact binomial upper bound for x successes in n."""
    if n <= 0:
        return float("nan")
    if x >= n:
        return 1.0
    from scipy.stats import beta
    return float(beta.ppf(1.0 - alpha, x + 1, n - x))


# --- identity audit ---------------------------------------------------------

def audit_identity(acts: dict) -> dict:
    """Verify __sol tensors are identical within problem, distinct across.

    acts: (problem_id, sample_idx) -> (L, d) float32 array."""
    by_pid: dict[str, list] = {}
    for (pid, _), a in sorted(acts.items()):
        by_pid.setdefault(pid, []).append(a)
    n_pairs = 0
    max_within = 0.0
    all_identical = True
    for arrs in by_pid.values():
        ref = arrs[0]
        for a in arrs[1:]:
            n_pairs += 1
            if not np.array_equal(ref, a):
                all_identical = False
                diff = np.abs(ref - a)
                max_within = max(max_within,
                                 float(np.nanmax(diff)) if np.isnan(diff).any()
                                 else float(diff.max()))
    reps = {pid: arrs[0] for pid, arrs in by_pid.items()}
    pids = sorted(reps)
    min_between = float("inf")
    for i, p in enumerate(pids):
        for q in pids[i + 1:]:
            min_between = min(min_between, float(np.linalg.norm(reps[p] - reps[q])))
    return {
        "n_problems": len(pids),
        "n_samples": len(acts),
        "n_within_problem_pairs": n_pairs,
        "all_within_problem_identical": all_identical,
        "max_within_problem_absdiff": max_within,
        "min_between_problem_l2": min_between if pids else float("nan"),
        "tensor_sha256_by_problem": {
            pid: hashlib.sha256(reps[pid].tobytes()).hexdigest() for pid in pids
        },
    }


# --- fast problem-level grouped CV (for the permutation null) ---------------

def _problem_folds(groups: list, k: int, seed: int) -> list[list]:
    """Problem-level folds identical to probe_mechinterp._make_folds(groups=...)."""
    uniq = np.array(sorted(set(groups)))
    rng = np.random.RandomState(seed)
    gfolds = np.array_split(rng.permutation(len(uniq)), min(k, len(uniq)))
    return [[uniq[i] for i in gf] for gf in gfolds]


def grouped_scores_from_problem_vecs(prob_vecs: np.ndarray, pids: list,
                                     y: np.ndarray, groups: list,
                                     folds: list[list]) -> np.ndarray:
    """Pooled held-out scores (n, L) for grouped CV, computed at problem level.

    Because every sample of a problem shares one vector, the train-fold class
    means equal label-count-weighted means over problem vectors — exact, and
    ~n_samples/n_problems times cheaper, which makes a 1000-permutation null
    tractable. Asserted against per_layer_auroc on the real data in run_arm().
    """
    pid_ix = {p: i for i, p in enumerate(pids)}
    g = np.array([pid_ix[p] for p in groups])
    n, (P, L, D) = len(y), prob_vecs.shape
    n1 = np.bincount(g, weights=(y == 1), minlength=P)
    n0 = np.bincount(g, weights=(y == 0), minlength=P)
    scores = np.full((n, L), np.nan)
    for fold in folds:
        te_p = np.array([pid_ix[p] for p in fold if p in pid_ix], dtype=int)
        if len(te_p) == 0:
            continue
        tr_mask = np.ones(P, bool)
        tr_mask[te_p] = False
        w1, w0 = n1 * tr_mask, n0 * tr_mask
        if w1.sum() == 0 or w0.sum() == 0:
            continue          # degenerate train fold — reference leaves NaN
        mu1 = np.einsum("p,pld->ld", w1, prob_vecs) / w1.sum()
        mu0 = np.einsum("p,pld->ld", w0, prob_vecs) / w0.sum()
        d = mu1 - mu0
        norm = np.linalg.norm(d, axis=1, keepdims=True)
        d = np.where(norm > 0, d / np.where(norm == 0, 1, norm), d)
        s_prob = np.einsum("pld,ld->pl", prob_vecs[te_p], d)
        for j, p in enumerate(te_p):
            scores[g == p] = s_prob[j]
    return scores


def _max_layer_auroc(scores: np.ndarray, y: np.ndarray) -> float:
    aurocs = []
    for l in range(scores.shape[1]):
        m = ~np.isnan(scores[:, l])
        aurocs.append(_auroc(scores[m, l], y[m]) if m.any() else float("nan"))
    arr = np.array(aurocs)
    return float(np.nanmax(arr)) if not np.all(np.isnan(arr)) else float("nan")


def reference_grouped_scores(X: np.ndarray, y: np.ndarray, groups: list,
                             *, k: int = 5, seed: int = 0) -> np.ndarray:
    """Pooled held-out scores (n, L) exactly as per_layer_auroc computes them
    (same folds, same mean-difference direction), returned instead of reduced
    to AUROCs — so the fast problem-level path can be validated score-by-score.

    Validation must happen at the score level, not the AUROC level: within a
    problem the __sol vectors are byte-identical, but `X[te] @ w` scores
    identical rows with ~1e-14 BLAS accumulation jitter, so the reference's
    within-problem ties are broken by floating-point noise before _auroc's
    tie handling can average them. The fast path scores each problem once,
    keeping the ties exact. Both are reported; the difference (~0.005 AUROC
    here) is itself a symptom of pretending n_samples > n_problems.
    """
    n, L, _ = X.shape
    folds = _make_folds(n, y, k, seed, groups=groups)
    scores = np.full((n, L), np.nan)
    for te in folds:
        if len(te) == 0:
            continue
        tr = np.setdiff1d(np.arange(n), te)
        if len(np.unique(y[tr])) < 2:
            continue
        for l in range(L):
            w = _meandiff_dir(X[tr, l, :], y[tr])
            scores[te, l] = X[te, l, :] @ w
    return scores


def perm_null_grouped_max(prob_vecs: np.ndarray, pids: list, y: np.ndarray,
                          groups: list, *, k: int = 5, seed: int = 0,
                          n_perms: int = 1000) -> dict:
    """Null for max-over-layers grouped-CV AUROC: permute which problem's
    activation vector is paired with which problem's label block. Preserves
    within-problem label clustering, block sizes, and fold structure — the
    exchangeability that the sample-level shuffle broke."""
    folds = _problem_folds(groups, k, seed)
    obs = _max_layer_auroc(
        grouped_scores_from_problem_vecs(prob_vecs, pids, y, groups, folds), y)
    rng = np.random.RandomState(seed + 20260712)
    null = []
    for _ in range(n_perms):
        pi = rng.permutation(len(pids))
        stat = _max_layer_auroc(
            grouped_scores_from_problem_vecs(prob_vecs[pi], pids, y, groups, folds), y)
        if not np.isnan(stat):
            null.append(stat)
    null = np.array(null)
    p = float((1 + (null >= obs).sum()) / (1 + len(null))) if len(null) else float("nan")
    return {
        "observed_grouped_max_auroc": obs,
        "n_perms_requested": n_perms,
        "n_perms_valid": int(len(null)),
        "p_value": p,
        "null_mean": float(null.mean()) if len(null) else float("nan"),
        "null_p50": float(np.percentile(null, 50)) if len(null) else float("nan"),
        "null_p95": float(np.percentile(null, 95)) if len(null) else float("nan"),
        "null_max": float(null.max()) if len(null) else float("nan"),
    }


def oracle_baserate_auroc(y: np.ndarray, groups: list) -> float:
    """AUROC of predicting each sample by its problem's FULL-DATA mean label.

    No activations involved. Note this reference includes the scored sample's
    own label in the mean, so it is an upper reference for problem-identity
    information, not a rate attainable by a CV-legal memorizer — for the
    attainable version see foldlegal_baserate_auroc."""
    means = {}
    g = np.array(groups)
    for p in set(groups):
        means[p] = float(y[g == p].mean())
    return _auroc(np.array([means[p] for p in groups]), y)


def foldlegal_baserate_auroc(y: np.ndarray, groups: list, *, k: int = 5,
                             seed: int = 0) -> float:
    """AUROC of a CV-LEGAL problem-identity memorizer under the same
    sample-level folds the published plain-CV probe used.

    Each held-out sample is scored by its problem's mean label among TRAIN
    samples only (falling back to the train global mean if the problem is
    absent from the train folds). This is exactly what duplicate leakage lets
    a probe achieve with zero information from the activations, computed
    without peeking at any test label."""
    g = np.array(groups)
    n = len(y)
    folds = _make_folds(n, y, k, seed, groups=None)
    scores = np.full(n, np.nan)
    for te in folds:
        if len(te) == 0:
            continue
        tr = np.setdiff1d(np.arange(n), te)
        gmean = float(y[tr].mean())
        for i in te:
            mask = g[tr] == g[i]
            scores[i] = float(y[tr][mask].mean()) if mask.any() else gmean
    m = ~np.isnan(scores)
    return _auroc(scores[m], y[m])


def problem_level_lopo(prob_vecs: np.ndarray, pids: list, y: np.ndarray,
                       groups: list, *, seed: int = 0,
                       n_perms: int = 2000) -> dict:
    """The honest unit of analysis: one vector, one label, per problem.

    Label = problem's majority sample label; leave-one-problem-out mean-diff
    probe; max-over-layers AUROC over the P problem scores, with a
    problem-label permutation p-value using the same max statistic.

    "Majority" is undefined for a problem whose samples split exactly 50/50
    (this occurs in the real data: base/functional_evasion has one such
    problem). Rather than let a rounding convention silently decide, both
    assignments are computed and reported: tie_as_neg (ties -> 0) and
    tie_as_pos (ties -> 1). The top-level fields mirror tie_as_neg for
    continuity with earlier output."""
    g = np.array(groups)
    means = np.array([float(y[g == p].mean()) for p in pids])
    n_tied = int((means == 0.5).sum())
    P, L, D = prob_vecs.shape

    def lopo_max(labels: np.ndarray) -> float:
        if labels.sum() < 2 or (1 - labels).sum() < 2:
            return float("nan")
        scores = np.full((P, L), np.nan)
        for i in range(P):
            tr = np.arange(P) != i
            if labels[tr].sum() == 0 or (1 - labels[tr]).sum() == 0:
                continue
            mu1 = prob_vecs[tr & (labels == 1)].mean(0)
            mu0 = prob_vecs[tr & (labels == 0)].mean(0)
            d = mu1 - mu0
            norm = np.linalg.norm(d, axis=1, keepdims=True)
            d = np.where(norm > 0, d / np.where(norm == 0, 1, norm), d)
            scores[i] = np.einsum("ld,ld->l", prob_vecs[i], d)
        return _max_layer_auroc(scores, labels)

    def run(labels: np.ndarray) -> dict:
        obs = lopo_max(labels)
        rng = np.random.RandomState(seed + 424242)
        null = []
        for _ in range(n_perms):
            stat = lopo_max(rng.permutation(labels))
            if not np.isnan(stat):
                null.append(stat)
        null = np.array(null)
        p = (float((1 + (null >= obs).sum()) / (1 + len(null)))
             if len(null) and not np.isnan(obs) else float("nan"))
        return {"n_pos_problems": int(labels.sum()),
                "observed_lopo_max_auroc": obs, "p_value": p,
                "n_perms_valid": int(len(null)),
                "null_p95": float(np.percentile(null, 95)) if len(null) else float("nan")}

    tie_neg = run((means > 0.5).astype(int))
    out = {"n_problems": P, "n_tied_problems": n_tied, "tie_as_neg": tie_neg,
           "n_pos_problems": tie_neg["n_pos_problems"],
           "observed_lopo_max_auroc": tie_neg["observed_lopo_max_auroc"],
           "p_value": tie_neg["p_value"],
           "n_perms_valid": tie_neg["n_perms_valid"],
           "null_p95": tie_neg["null_p95"]}
    if n_tied:
        out["tie_as_pos"] = run((means >= 0.5).astype(int))
    return out


