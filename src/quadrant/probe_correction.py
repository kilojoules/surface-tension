"""Corrected __sol probe statistics (correction of 2026-07-12).

Why this module exists: the __sol activation is captured by a dedicated
forward pass over the SOLUTION PROMPT ONLY (scripts/quadrant_pod_runner.py),
and the solution prompt is a function of (model, problem) alone — it does not
vary with sample_idx, and temperature only enters at generation. The __sol
tensor is therefore deterministic per (model, problem): every sample of a
problem shares one vector. Three consequences, verified here:

1. IDENTITY AUDIT — within-(arm, problem) __sol tensors are byte-identical,
   so the probe has as many distinct inputs as PROBLEMS, not samples. It
   cannot in principle predict which GENERATION launders — only a per-problem
   propensity. (The README's "within-problem variance" control, 9/16 problems
   mixed, is therefore evidence AGAINST the per-generation-plan reading: the
   probe assigns identical scores to samples that behave differently.)
2. LEAKAGE — sample-level k-fold CV places byte-identical copies of a
   problem's vector in both train and test folds; the published 0.82 is
   inflated by problem-identity memorization (an oracle that scores each
   sample by its problem's full-data mean label reaches ~0.9 with no
   activations at all). The leakage-free number is the problem-held-out
   (grouped) CV.
3. SELECTION NULL — the published "shuffle null (~0.6)" permuted labels at
   the SAMPLE level (probe_mechinterp.per_layer_auroc shuffle=True), which
   destroys the within-problem label clustering that drives max-over-61-layers
   selection noise at an effective n of ~16 problems. The correct null
   permutes the problem -> activation-vector pairing, preserving each
   problem's label multiset and the grouped-CV structure. This module runs
   that null (default 1000 permutations) and reports the p-value.

It also computes exact Clopper-Pearson upper bounds for the Stage-3 deception
counts, which were published as bare point estimates ("0.000") without the
problem-level bootstrap CIs the prereg specified. The judge outputs (claim
side) were lost when the judge pod was deleted, so the counts themselves are
as published in commit be5edf1 and cannot currently be re-derived; the
fact-side rows, self-report texts, and __sol tensors are published under
data/evidence/quadrant_v4/ (see package_evidence.py) so everything on the
fact side — including every number in this module — is independently
auditable, and the claim side can be regenerated by re-running a judge over
the published self_report_text fields.

Every published Stage-3 probe number is first REPRODUCED with the repo's own
per_layer_auroc (same folds, same seed; exact under the author's raw file
enumeration order — the plain-CV/shuffle figures are order-dependent, which
is itself documented in the correction §3d) before the corrected statistics
are computed. The corrected statistics are order-invariant by construction,
and the fast problem-level implementation used for the permutation null is
asserted against the reference score-by-score on the real data.

Run (packaged evidence, the auditable path):
    python -m quadrant.probe_correction --evidence data/evidence/quadrant_v4 \
        --out results/correction_2026-07-12
Run (raw pod-sync layout, author machine):
    python -m quadrant.probe_correction --raw --out results/correction_2026-07-12
"""
