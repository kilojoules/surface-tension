def _cli():
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    src = ap.add_mutually_exclusive_group(required=True)
    src.add_argument("--evidence", help="data/evidence/quadrant_v4 directory")
    src.add_argument("--raw", action="store_true",
                     help="read the raw pod-sync layout in RAW_MANIFEST")
    ap.add_argument("--arms", nargs="*", default=list(RAW_MANIFEST))
    ap.add_argument("--n-perms", type=int, default=1000)
    ap.add_argument("--rep", action="store_true",
                    help="analyze the __rep position instead (raw source only; "
                         "__rep tensors are not packaged — see the evidence README)")
    ap.add_argument("--out", required=True, help="output directory")
    args = ap.parse_args()
    if args.rep and args.evidence:
        ap.error("--rep requires --raw: __rep tensors are not in the evidence package")

    os.makedirs(args.out, exist_ok=True)
    if args.rep:
        results = {"arms": {}}
        for arm in args.arms:
            acts = load_activations(
                os.path.join(RAW_MANIFEST[arm], "activations"), "rep")
            rows = load_rows(os.path.join(
                RAW_MANIFEST[arm], "paper/data/quadrant/self_reports.jsonl"))
            print(f"[{arm}] {len(acts)} __rep tensors, {len(rows)} rows")
            results["arms"][arm] = run_arm_rep(arm, acts, rows)
        path = os.path.join(args.out, "probe_correction_rep_raw.json")
        with open(path, "w") as f:
            json.dump(_sanitize_nan(results), f, indent=2, sort_keys=True,
                      allow_nan=False)
        print(f"wrote {path}")
        return 0

    results = {"deception_upper_bounds": deception_bounds(), "arms": {}}
    for arm in args.arms:
        if args.evidence:
            acts, rows = load_arm_evidence(args.evidence, arm)
        else:
            acts, rows = load_arm_raw(RAW_MANIFEST[arm])
        print(f"[{arm}] {len(acts)} __sol tensors, {len(rows)} rows")
        results["arms"][arm] = run_arm(arm, acts, rows, n_perms=args.n_perms)
        hl = results["arms"][arm]["probes"].get(HEADLINE_LABEL, {})
        pub, pn = hl.get("published_config", {}), hl.get("problem_permutation_null", {})
        if pub:
            fmt = lambda v, spec: (f"{v:{spec}}" if isinstance(v, float) else str(v))
            print(f"  {HEADLINE_LABEL}: plain {fmt(pub.get('plain_cv_max_auroc'), '.3f')} "
                  f"grouped {fmt(pub.get('grouped_cv_max_auroc'), '.3f')} "
                  f"perm-p {fmt(pn.get('p_value'), '.4f')} "
                  f"(null p95 {fmt(pn.get('null_p95'), '.3f')})")
    src_label = "evidence" if args.evidence else "raw"
    path = os.path.join(args.out, f"probe_correction_{src_label}.json")
    with open(path, "w") as f:
        json.dump(_sanitize_nan(results), f, indent=2, sort_keys=True,
                  allow_nan=False)
    print(f"wrote {path}")
    return 0


if __name__ == "__main__":
    import sys
    sys.exit(_cli())
