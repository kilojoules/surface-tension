import sys
from itertools import permutations

def solve():
    # Read all input at once and split into a flat list of integers
    input_data = map(int, sys.stdin.read().split())
    
    # Use a generator to consume the input stream
    gen = input_data
    
    # N is the first element
    N = next(gen)
    
    # Read G edges
    Mg = next(gen)
    g_edges = [tuple(sorted((next(gen), next(gen)))) for _ in range(Mg)]
    
    # Read H edges
    Mh = next(gen)
    h_edges = [tuple(sorted((next(gen), next(gen)))) for _ in range(Mh)]
    
    # Read A matrix
    # The A values are given as A_{1,2}, A_{1,3}... A_{1,N}, A_{2,3}...
    # We store them in a dictionary with sorted tuple keys for easy lookup
    # There are N*(N-1)//2 such values
    a_values = [next(gen) for _ in range(N * (N - 1) // 2)]
    
    # Map the flat A list to (i, j) pairs
    # i ranges from 1 to N-1, j ranges from i+1 to N
    a_map = {}
    idx = 0
    for i in range(1, N + 1):
        for j in range(i + 1, N + 1):
            a_map[(i, j)] = a_values[idx]
            idx += 1

    # Represent graphs as sets of sorted tuples for O(1) lookup
    set_g = set(g_edges)
    set_h = set(h_edges)

    # We need to find a permutation P of (1...N) that minimizes the cost
    # The cost for a permutation P is the sum of A_{P_i, P_j} for all pairs (i, j)
    # where the edge existence in G(i, j) differs from edge existence in H(P_i, P_j)
    
    # Pre-calculate all pairs (i, j) with 1 <= i < j <= N
    all_pairs = [(i, j) for i in range(1, N + 1) for j in range(i + 1, N + 1)]
    
    # Try all permutations of (1...N)
    # For each permutation P, the cost is:
    # sum(A_{P_i, P_j} if (edge(i,j) in G != edge(P_i, P_j) in H))
    
    # To optimize, we use a helper to get the sorted pair
    def get_pair(u, v):
        return (u, v) if u < v else (v, u)

    # We use a list comprehension inside min() to avoid explicit loops
    # Permutations are generated by itertools.permutations
    # We map the permutation to the total cost
    
    # Note: P is a tuple where P[i-1] is the image of vertex i
    # For a pair (i, j) in G, the corresponding pair in H is (P[i-1], P[j-1])
    
    ans = min(
        sum(
            a_map[get_pair(p[i-1], p[j-1])] 
            for i, j in all_pairs 
            if ((i, j) in set_g) != (get_pair(p[i-1], p[j-1]) in set_h)
        )
        for p in permutations(range(1, N + 1))
    )
    
    print(ans)

if __name__ == "__main__":
    solve()