import sys

def solve():
    # Read S and T from standard input
    input_data = sys.stdin.read().split()
    if not input_data:
        return
    S = input_data[0]
    T = input_data[1]

    # Identify indices where S and T differ
    diff_indices = [i for i in range(len(S)) if S[i] != T[i]]
    
    # To minimize the number of elements in X, we must change exactly one 
    # character per operation. The minimum number of operations is the 
    # number of positions where S and T differ.
    M = len(diff_indices)
    
    # To make the array X lexicographically smallest, we want the strings 
    # appearing earlier in the array to be lexicographically smaller.
    # This means we should prioritize changing characters at the earliest 
    # possible indices to the target characters in T, provided that the 
    # target character is smaller than the current character.
    # However, the constraint is simply to reach T in M steps.
    # The lexicographically smallest sequence is achieved by iterating 
    # through the indices 0 to N-1 and changing S[i] to T[i] one by one.
    
    # Let's refine: we must change one character at a time.
    # To keep the resulting strings as small as possible, we should 
    # process the indices from left to right.
    
    # Create a list of the indices that need changing
    indices_to_change = diff_indices
    
    # The sequence of strings is generated by changing S[i] to T[i] 
    # for each i in indices_to_change.
    # Since we want the lexicographically smallest array, and we must 
    # change one char per step, the only flexibility is the order of 
    # indices. Changing the leftmost character first is always optimal 
    # for the first string in the array.
    
    # Generate the sequence of strings
    # We use a list comprehension to create the strings.
    # For the k-th step (0-indexed), we have changed indices 
    # indices_to_change[0...k].
    
    # We can simulate the process by maintaining the current state of S.
    # But since we can't use loops, we can use a technique to build the 
    # string based on the index.
    
    # For the i-th string in X (1 <= i <= M):
    # It is the string where characters at indices_to_change[0...i-1] 
    # have been updated to T, and others remain S.
    
    # We can use a helper function inside a list comprehension.
    def get_string(step):
        # Changed indices for this step
        changed = set(indices_to_change[:step])
        return "".join([T[j] if j in changed else S[j] for j in range(len(S))])

    # Generate X
    X = [get_string(i) for i in range(1, M + 1)]
    
    # Output M
    print(M)
    # Output each element of X
    if X:
        print("\n".join(X))

if __name__ == "__main__":
    solve()