import sys
from itertools import product

def solve():
    # Read input
    input_data = sys.stdin.read().split()
    if not input_data:
        return
    
    n = int(input_data[0])
    h = list(map(int, input_data[1:]))

    # We need to find the maximum number of buildings with the same height 
    # placed at equal intervals.
    # A combination is defined by:
    # 1. The starting index 'i' (0 to n-1)
    # 2. The interval 'd' (1 to n-1)
    # 3. The height 'height' we are looking for.
    
    # However, it's more efficient to iterate over:
    # i: starting index
    # d: interval
    # Then check if the buildings at i, i+d, i+2d... have the same height.
    
    # To avoid loops, we use itertools.product to generate (i, d) pairs.
    # For each (i, d), we extract the sequence of heights.
    # We then check if all elements in that sequence are identical.
    
    # Since we need the maximum count, we can evaluate all valid (i, d) pairs.
    # Note: if d is too large, the sequence length is 1.
    
    # Generate all possible starting positions and intervals
    # i ranges from 0 to n-1, d ranges from 1 to n
    params = product(range(n), range(1, n + 1))
    
    # For a fixed i and d, the indices are i, i+d, i+2d... 
    # The number of elements is (n - 1 - i) // d + 1
    # We check if all heights at these indices are equal to h[i].
    
    # We use a helper function logic inside a list comprehension.
    # For a given (i, d), we create the list of heights: [h[i + k*d] for k in range(...) if i + k*d < n]
    # Then we check if the set of these heights has size 1.
    
    # To avoid 'for' in range() inside the comprehension, we can use a list 
    # of indices generated by a slice: h[i::d]
    
    # We calculate the length of the slice if all elements in the slice are the same.
    # Otherwise, we can't just say 0 because a single building is always valid.
    # But the slice h[i::d] always has at least one element (h[i]).
    
    # The condition "all elements are the same" is: len(set(h[i::d])) == 1
    
    # We calculate the lengths of all such valid slices and take the max.
    # We use a generator expression inside max() to find the result.
    
    ans = max([
        len(slice_h) for i, d in product(range(n), range(1, n + 1))
        for slice_h in [h[i::d]]
        if len(set(slice_h)) == 1
    ] + [1]) # + [1] handles the case where N=0 or other edge cases, though N >= 1
    
    print(ans)

if __name__ == "__main__":
    solve()