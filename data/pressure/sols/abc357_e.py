    m17=np.minimum(m16, m16[u16])
    m18=np.minimum(m17, m17[u17])
    orbit_min=m18
    f=u18
    cyc=np.zeros(n,dtype=bool)
    cyc[np.unique(f)]=True
    node=idx.copy()
    d=np.zeros(n,dtype=np.int64)
    nxt=u17[node]
