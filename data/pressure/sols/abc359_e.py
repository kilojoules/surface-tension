import sys
import numpy as np

def main():
    data = sys.stdin.buffer.read().split()
    N = int(data[0])
    H = np.array(data[1:1 + N], dtype=np.int64)
    if N == 1:
        sys.stdout.write(str(int(H[0]) + 1) + ' \n')
        return
    idx = np.arange(N)
    Nm1 = N - 1

    # forward sparse max-table F[k][i] = max H[i .. i+2^k-1] (clamped)
    F0 = H
    F1 = np.maximum(F0, F0[np.minimum(idx + 1, Nm1)])
    F2 = np.maximum(F1, F1[np.minimum(idx + 2, Nm1)])
    F3 = np.maximum(F2, F2[np.minimum(idx + 4, Nm1)])
    F4 = np.maximum(F3, F3[np.minimum(idx + 8, Nm1)])
    F5 = np.maximum(F4, F4[np.minimum(idx + 16, Nm1)])
    F6 = np.maximum(F5, F5[np.minimum(idx + 32, Nm1)])
    F7 = np.maximum(F6, F6[np.minimum(idx + 64, Nm1)])
    F8 = np.maximum(F7, F7[np.minimum(idx + 128, Nm1)])
    F9 = np.maximum(F8, F8[np.minimum(idx + 256, Nm1)])
    F10 = np.maximum(F9, F9[np.minimum(idx + 512, Nm1)])
    F11 = np.maximum(F10, F10[np.minimum(idx + 1024, Nm1)])
    F12 = np.maximum(F11, F11[np.minimum(idx + 2048, Nm1)])
    F13 = np.maximum(F12, F12[np.minimum(idx + 4096, Nm1)])
    F14 = np.maximum(F13, F13[np.minimum(idx + 8192, Nm1)])
    F15 = np.maximum(F14, F14[np.minimum(idx + 16384, Nm1)])
    F16 = np.maximum(F15, F15[np.minimum(idx + 32768, Nm1)])
    F17 = np.maximum(F16, F16[np.minimum(idx + 65536, Nm1)])

    # backward sparse max-table G[k][i] = max H[i-2^k+1 .. i] (clamped)
    G0 = H
    G1 = np.maximum(G0, G0[np.maximum(idx - 1, 0)])
    G2 = np.maximum(G1, G1[np.maximum(idx - 2, 0)])
    G3 = np.maximum(G2, G2[np.maximum(idx - 4, 0)])
    G4 = np.maximum(G3, G3[np.maximum(idx - 8, 0)])
    G5 = np.maximum(G4, G4[np.maximum(idx - 16, 0)])
    G6 = np.maximum(G5, G5[np.maximum(idx - 32, 0)])
    G7 = np.maximum(G6, G6[np.maximum(idx - 64, 0)])
    G8 = np.maximum(G7, G7[np.maximum(idx - 128, 0)])
    G9 = np.maximum(G8, G8[np.maximum(idx - 256, 0)])
    G10 = np.maximum(G9, G9[np.maximum(idx - 512, 0)])
    G11 = np.maximum(G10, G10[np.maximum(idx - 1024, 0)])
    G12 = np.maximum(G11, G11[np.maximum(idx - 2048, 0)])
    G13 = np.maximum(G12, G12[np.maximum(idx - 4096, 0)])
    G14 = np.maximum(G13, G13[np.maximum(idx - 8192, 0)])
    G15 = np.maximum(G14, G14[np.maximum(idx - 16384, 0)])
    G16 = np.maximum(G15, G15[np.maximum(idx - 32768, 0)])
    G17 = np.maximum(G16, G16[np.maximum(idx - 65536, 0)])

    # next greater-or-equal R[i]: smallest j>i with H[j] >= H[i], else N
    pos = idx + 1
    posc = np.minimum(pos, Nm1)
    cond = (pos + 131072 <= N) & (F17[posc] < H)
    pos = pos + np.where(cond, 131072, 0)
    posc = np.minimum(pos, Nm1)
    cond = (pos + 65536 <= N) & (F16[posc] < H)
    pos = pos + np.where(cond, 65536, 0)
    posc = np.minimum(pos, Nm1)
    cond = (pos + 32768 <= N) & (F15[posc] < H)
    pos = pos + np.where(cond, 32768, 0)
    posc = np.minimum(pos, Nm1)
    cond = (pos + 16384 <= N) & (F14[posc] < H)
    pos = pos + np.where(cond, 16384, 0)
    posc = np.minimum(pos, Nm1)
    cond = (pos + 8192 <= N) & (F13[posc] < H)
    pos = pos + np.where(cond, 8192, 0)
    posc = np.minimum(pos, Nm1)
    cond = (pos + 4096 <= N) & (F12[posc] < H)
    pos = pos + np.where(cond, 4096, 0)
    posc = np.minimum(pos, Nm1)
    cond = (pos + 2048 <= N) & (F11[posc] < H)
    pos = pos + np.where(cond, 2048, 0)
    posc = np.minimum(pos, Nm1)
    cond = (pos + 1024 <= N) & (F10[posc] < H)
    pos = pos + np.where(cond, 1024, 0)
    posc = np.minimum(pos, Nm1)
    cond = (pos + 512 <= N) & (F9[posc] < H)
    pos = pos + np.where(cond, 512, 0)
    posc = np.minimum(pos, Nm1)
    cond = (pos + 256 <= N) & (F8[posc] < H)
    pos = pos + np.where(cond, 256, 0)
    posc = np.minimum(pos, Nm1)
    cond = (pos + 128 <= N) & (F7[posc] < H)
    pos = pos + np.where(cond, 128, 0)
    posc = np.minimum(pos, Nm1)
    cond = (pos + 64 <= N) & (F6[posc] < H)
    pos = pos + np.where(cond, 64, 0)
    posc = np.minimum(pos, Nm1)
    cond = (pos + 32 <= N) & (F5[posc] < H)
    pos = pos + np.where(cond, 32, 0)
    posc = np.minimum(pos, Nm1)
    cond = (pos + 16 <= N) & (F4[posc] < H)
    pos = pos + np.where(cond, 16, 0)
    posc = np.minimum(pos, Nm1)
    cond = (pos + 8 <= N) & (F3[posc] < H)
    pos = pos + np.where(cond, 8, 0)
    posc = np.minimum(pos, Nm1)
    cond = (pos + 4 <= N) & (F2[posc] < H)
    pos = pos + np.where(cond, 4, 0)
    posc = np.minimum(pos, Nm1)
    cond = (pos + 2 <= N) & (F1[posc] < H)
    pos = pos + np.where(cond, 2, 0)
    posc = np.minimum(pos, Nm1)
    cond = (pos + 1 <= N) & (F0[posc] < H)
    pos = pos + np.where(cond, 1, 0)
    R = pos

    # previous strictly-greater L[i]: largest j<i with H[j] > H[i], else -1
    pos = idx - 1
    posc = np.maximum(pos, 0)
    cond = (pos - 131072 + 1 >= 0) & (G17[posc] <= H)
    pos = pos - np.where(cond, 131072, 0)
    posc = np.maximum(pos, 0)
    cond = (pos - 65536 + 1 >= 0) & (G16[posc] <= H)
    pos = pos - np.where(cond, 65536, 0)
    posc = np.maximum(pos, 0)
    cond = (pos - 32768 + 1 >= 0) & (G15[posc] <= H)
    pos = pos - np.where(cond, 32768, 0)
    posc = np.maximum(pos, 0)
    cond = (pos - 16384 + 1 >= 0) & (G14[posc] <= H)
    pos = pos - np.where(cond, 16384, 0)
    posc = np.maximum(pos, 0)
    cond = (pos - 8192 + 1 >= 0) & (G13[posc] <= H)
    pos = pos - np.where(cond, 8192, 0)
    posc = np.maximum(pos, 0)
    cond = (pos - 4096 + 1 >= 0) & (G12[posc] <= H)
    pos = pos - np.where(cond, 4096, 0)
    posc = np.maximum(pos, 0)
    cond = (pos - 2048 + 1 >= 0) & (G11[posc] <= H)
    pos = pos - np.where(cond, 2048, 0)
    posc = np.maximum(pos, 0)
    cond = (pos - 1024 + 1 >= 0) & (G10[posc] <= H)
    pos = pos - np.where(cond, 1024, 0)
    posc = np.maximum(pos, 0)
    cond = (pos - 512 + 1 >= 0) & (G9[posc] <= H)
    pos = pos - np.where(cond, 512, 0)
    posc = np.maximum(pos, 0)
    cond = (pos - 256 + 1 >= 0) & (G8[posc] <= H)
    pos = pos - np.where(cond, 256, 0)
    posc = np.maximum(pos, 0)
    cond = (pos - 128 + 1 >= 0) & (G7[posc] <= H)
    pos = pos - np.where(cond, 128, 0)
    posc = np.maximum(pos, 0)
    cond = (pos - 64 + 1 >= 0) & (G6[posc] <= H)
    pos = pos - np.where(cond, 64, 0)
    posc = np.maximum(pos, 0)
    cond = (pos - 32 + 1 >= 0) & (G5[posc] <= H)
    pos = pos - np.where(cond, 32, 0)
    posc = np.maximum(pos, 0)
    cond = (pos - 16 + 1 >= 0) & (G4[posc] <= H)
    pos = pos - np.where(cond, 16, 0)
    posc = np.maximum(pos, 0)
    cond = (pos - 8 + 1 >= 0) & (G3[posc] <= H)
    pos = pos - np.where(cond, 8, 0)
    posc = np.maximum(pos, 0)
    cond = (pos - 4 + 1 >= 0) & (G2[posc] <= H)
    pos = pos - np.where(cond, 4, 0)
    posc = np.maximum(pos, 0)
    cond = (pos - 2 + 1 >= 0) & (G1[posc] <= H)
    pos = pos - np.where(cond, 2, 0)
    posc = np.maximum(pos, 0)
    cond = (pos - 1 + 1 >= 0) & (G0[posc] <= H)
    pos = pos - np.where(cond, 1, 0)
    L = pos

    # element k is max of [j,i] for j in (L,k], i in [k,R); adds H_k*(k-L) to E_i
    c = H * (idx - L)
    diff = np.zeros(N + 1, dtype=np.int64)
    np.add.at(diff, idx, c)
    np.add.at(diff, R, -c)
    E = np.cumsum(diff[:N])
    ans = E + 1
    sys.stdout.write(' '.join(np.char.mod('%d', ans)) + ' \n')


main()
